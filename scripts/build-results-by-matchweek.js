#!/usr/bin/env node
/* Build content/results-by-matchweek.json.

   content/results.json holds every verified full-time score but has no round
   number on it; the fixture files hold the 34/38-matchweek calendar. This joins
   the two so the Sports UI can group results by "Matchweek 1", "Matchweek 2"...
   instead of listing them as one undifferentiated pile.

   Every score keeps its source URL — results.json is the sourced-result
   pipeline and nothing here invents a scoreline. */
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const R = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const FIXTURES = {
  'premier-league': 'content/fixtures.json',
  'la-liga':        'content/fixtures-la-liga.json',
  'serie-a':        'content/fixtures-serie-a.json',
  'bundesliga':     'content/fixtures-bundesliga.json',
  'ligue-1':        'content/fixtures-ligue-1.json'
};

const results = R('content/results.json');
const comps = {};
R('content/competitions.json').competitions.forEach(c => { comps[c.id] = c; });

/* team display name + crest, taken from the league table so the UI matches
   the rest of the site rather than re-deriving names from slugs */
function teamIndex(compId) {
  const idx = {};
  ((comps[compId] || {}).teams || []).forEach(t => {
    idx[norm(t.name)] = { name: t.short || t.name, logo: t.logo };
  });
  return idx;
}
const norm = s => String(s || '').toLowerCase()
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '');

const out = { _comment: 'Generated by scripts/build-results-by-matchweek.js — do not edit by hand.', leagues: {} };
let total = 0;

Object.keys(FIXTURES).forEach(lg => {
  const fx = R(FIXTURES[lg]);
  const idx = teamIndex(lg);
  const played = results[lg] || {};

  // slug -> { number, match }
  const bySlug = {};
  (fx.matchweeks || []).forEach(w => {
    (w.matches || []).forEach(m => {
      bySlug[m.id + '-vs-' + m.away] = { number: w.number, m };
    });
  });

  const weeks = new Map();
  Object.keys(played).forEach(slug => {
    const hit = bySlug[slug];
    if (!hit) { console.warn('  unmapped result:', lg, slug); return; }
    const r = played[slug], m = hit.m;
    const h = idx[norm(m.homeName)] || { name: m.homeName, logo: '' };
    const a = idx[norm(m.awayName)] || { name: m.awayName, logo: '' };
    if (!weeks.has(hit.number)) weeks.set(hit.number, []);
    weeks.get(hit.number).push({
      slug,
      home: h.name, away: a.name,
      homeLogo: h.logo, awayLogo: a.logo,
      homeScore: r.homeScore, awayScore: r.awayScore,
      status: r.status || 'FT',
      playedOn: r.playedOn || m.date || '',
      source: r.source || null,
      scorers: r.scorers || []
    });
    total++;
  });

  const list = [...weeks.keys()].sort((x, y) => y - x).map(n => ({
    number: n,
    label: 'Matchweek ' + n,
    played: weeks.get(n).sort((p, q) => String(p.playedOn).localeCompare(String(q.playedOn))),
    total: ((fx.matchweeks || []).find(w => w.number === n) || {}).matches?.length || null
  }));

  out.leagues[lg] = {
    name: (comps[lg] || {}).name || fx.league || lg,
    season: fx.season || '',
    totalMatchweeks: (fx.matchweeks || []).length,
    resultCount: Object.keys(played).length,
    matchweeks: list
  };
});

fs.writeFileSync(path.join(root, 'content/results-by-matchweek.json'), JSON.stringify(out, null, 2) + '\n');
console.log('results-by-matchweek.json: %d results across %d leagues', total, Object.keys(out.leagues).length);
Object.entries(out.leagues).forEach(([k, v]) =>
  console.log('  %-16s %2d results in matchweeks %s', k, v.resultCount,
    v.matchweeks.map(w => w.number).join(', ')));
